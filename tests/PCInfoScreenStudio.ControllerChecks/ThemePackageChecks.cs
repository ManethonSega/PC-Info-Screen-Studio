using System.IO;
using System.IO.Compression;
using System.Security.Cryptography;
using System.Text.Json;
using System.Text.Json.Serialization;
using PCInfoScreenStudio.Models;
using PCInfoScreenStudio.Services;
using PCInfoScreenStudio.Controllers;
using PCInfoScreenStudio.ViewModels;

internal static class ThemePackageChecks
{
    private static readonly JsonSerializerOptions Json = new() { Converters = { new JsonStringEnumConverter() } };
    private static void Require(bool value, string message) { if (!value) throw new InvalidOperationException(message); }

    public static void Check(string root, Action<Task> awaitTask)
    {
        CheckLargeLegacyPackage(root, awaitTask);
        CheckUnusedMediaAndUndo(root, awaitTask);
        CheckBudgetAndFailures(root, awaitTask);
        CheckEditingDuringSave(root, awaitTask);
        CheckInactiveEmbeddedPhotoSession(root, awaitTask);
        Console.WriteLine("PASS: legacy themes over 1 GiB, save/load symmetry, unused-media cleanup, hidden/Hybrid/photo/font retention, Undo source preservation, package limits, cancellation and atomic failure cleanup.");
    }

    private static void CheckLargeLegacyPackage(string root, Action<Task> awaitTask)
    {
        var document = new ThemeDocument { Name = "Legacy large Info Screen" };
        for (var i = 0; i < 4; i++)
        {
            var asset = new ThemeAsset { Kind = ThemeAssetKind.Video, PackagePath = $"assets/video/large-{i}.mp4", OriginalFileName = $"large-{i}.mp4" };
            document.Assets.Add(asset);
            var widget = new WidgetModel { Type = WidgetType.Video, AssetId = asset.Id, IsVisible = i != 2 };
            if (i == 3) document.HybridWidgets.Add(widget); else document.Widgets.Add(widget);
        }
        var path = Path.Combine(root, "legacy-over-1gib.t3theme");
        const long length = 256L * 1024 * 1024 + 1; // Four legal-size video entries exceed the old total ceiling.
        // Generated byte payloads test the package container, not codecs or playback.
        var creating = Task.Run(async () => {
            using var zip = ZipFile.Open(path, ZipArchiveMode.Create);
            using (var json = zip.CreateEntry("theme.json").Open()) JsonSerializer.Serialize(json, document, Json);
            var zeros = new byte[1024 * 1024];
            foreach (var asset in document.Assets)
            {
                await using var stream = zip.CreateEntry(asset.PackagePath, CompressionLevel.Fastest).Open();
                long remaining = length;
                while (remaining > 0) { var count = (int)Math.Min(remaining, zeros.Length); await stream.WriteAsync(zeros.AsMemory(0, count)); remaining -= count; }
            }
        });
        awaitTask(creating);
        var hash = SHA256.HashData(File.ReadAllBytes(path));
        var package = new ThemePackageService(); var loading = package.LoadAsync(path); awaitTask(loading);
        using var loaded = loading.Result;
        Require(loaded.Document.Assets.Count == 4 && loaded.Document.Widgets.Count == 3 && loaded.Document.HybridWidgets.Count == 1,
            "Large legacy theme must keep visible, hidden and Hybrid layers");
        Require(loaded.Document.Assets.Sum(a => new FileInfo(loaded.GetAbsolutePath(a)).Length) == length * 4, "All referenced payloads survive the old 1 GiB boundary");
        Require(SHA256.HashData(File.ReadAllBytes(path)).SequenceEqual(hash), "Opening must never modify the original package");
        var savedPath = Path.Combine(root, "large-roundtrip.t3theme");
        var saving = package.SaveAsync(loaded, savedPath);
        loaded.Document.Name = "Edited while saving";
        awaitTask(saving);
        Require(loaded.IsDirty, "An edit during a background save must stay unsaved");
        var reopenedTask = package.LoadAsync(savedPath); awaitTask(reopenedTask);
        using var reopened = reopenedTask.Result;
        Require(reopened.Document.Name == "Legacy large Info Screen", "Saved package uses the original frozen document snapshot");
        Require(reopened.Document.Assets.Count == 4 && reopened.Document.Assets.All(a => new FileInfo(reopened.GetAbsolutePath(a)).Length == length), "A saved large package must reopen with identical asset lengths");
        Console.WriteLine($"PASS: generated legacy package with {length * 4} expanded bytes opens and saves/reopens above 1 GiB.");
    }

    private static void CheckUnusedMediaAndUndo(string root, Action<Task> awaitTask)
    {
        var package = new ThemePackageService(); using var workspace = package.CreateNewWorkspace();
        var importer = new AssetImportService();
        var fixture = Path.Combine(AppContext.BaseDirectory, "Fixtures", "video-colours.mp4");
        var video = importer.Import(workspace, fixture, ThemeAssetKind.Video);
        var removed = importer.Import(workspace, fixture, ThemeAssetKind.Video);
        var fontPath = Path.Combine(root, "palette.ttf"); File.WriteAllText(fontPath, "generated container font payload");
        var font = importer.Import(workspace, fontPath, ThemeAssetKind.Font);
        var imagePath = Path.Combine(root, "embedded.png"); File.WriteAllText(imagePath, "generated container image payload");
        var image = importer.Import(workspace, imagePath, ThemeAssetKind.Image);
        workspace.Document.Widgets.Add(new WidgetModel { Type = WidgetType.Video, AssetId = video.Id });
        workspace.Document.PhotoFrame.Photos.Add(new PhotoFrameItem { AssetId = image.Id });
        var liveCount = workspace.Document.Assets.Count;
        var path = Path.Combine(root, "trimmed.t3theme");
        awaitTask(package.SaveAsync(workspace, path));
        Require(workspace.Document.Assets.Count == liveCount && File.Exists(workspace.GetAbsolutePath(removed)), "Save must keep the live asset and file for Undo");
        using (var zip = ZipFile.OpenRead(path)) Require(zip.GetEntry(removed.PackagePath) is null && zip.GetEntry(font.PackagePath) is not null && zip.GetEntry(image.PackagePath) is not null, "Package skips removed media but keeps font palette and embedded photo");
        var loading = package.LoadAsync(path); awaitTask(loading);
        using (var loaded = loading.Result) Require(loaded.Document.Assets.Count == 3 && loaded.Document.PhotoFrame.Photos.Single().AssetId == image.Id, "Cleaned metadata matches retained files");
        workspace.Document.Widgets.Add(new WidgetModel { Type = WidgetType.Video, AssetId = removed.Id });
        awaitTask(package.SaveAsync(workspace, path));
        using (var zip = ZipFile.OpenRead(path)) Require(zip.GetEntry(removed.PackagePath) is not null, "Restoring a deleted widget can re-embed its original source");

        // Older packages retain assets without any widget reference. Do not inflate their bodies.
        var legacyPath = Path.Combine(root, "legacy-unused.t3theme");
        using (var zip = ZipFile.Open(legacyPath, ZipArchiveMode.Create))
        {
            var old = new ThemeDocument { Name = "Only text remains" };
            old.Widgets.Add(new WidgetModel { Type = WidgetType.Text, Label = "Kept layout" });
            old.Assets.Add(new ThemeAsset { Kind = ThemeAssetKind.Video, PackagePath = "assets/video/unused.mp4" });
            using (var json = zip.CreateEntry("theme.json").Open()) JsonSerializer.Serialize(json, old, Json);
            zip.CreateEntry("assets/video/unused.mp4");
        }
        SetDeclaredLengths(legacyPath, 2L * 1024 * 1024 * 1024); // Known orphan, larger than the old loader budget.
        var legacyLoading = package.LoadAsync(legacyPath); awaitTask(legacyLoading);
        using var legacy = legacyLoading.Result;
        Require(legacy.Document.Assets.Count == 0 && legacy.Document.Widgets.Single().Label == "Kept layout" && !Directory.EnumerateFiles(legacy.RootDirectory, "*", SearchOption.AllDirectories).Any(), "Legacy unused imports are omitted before extraction");
    }

    private static void CheckBudgetAndFailures(string root, Action<Task> awaitTask)
    {
        var package = new ThemePackageService();
        var path = Path.Combine(root, "over-budget.t3theme");
        using (var zip = ZipFile.Open(path, ZipArchiveMode.Create))
        {
            var document = new ThemeDocument();
            for (var i = 0; i < 5; i++)
            {
                var asset = new ThemeAsset { Kind = ThemeAssetKind.Video, PackagePath = $"assets/video/{i}.mp4" };
                document.Assets.Add(asset); document.Widgets.Add(new WidgetModel { Type = WidgetType.Video, AssetId = asset.Id });
                zip.CreateEntry(asset.PackagePath);
            }
            using var json = zip.CreateEntry("theme.json").Open(); JsonSerializer.Serialize(json, document, Json);
        }
        SetDeclaredLengths(path, 1024L * 1024 * 1024);
        ExpectInvalid(package.LoadAsync(path), awaitTask, "4 GiB");
        var malformed = Path.Combine(root, "false-length.t3theme");
        using (var zip = ZipFile.Open(malformed, ZipArchiveMode.Create))
        {
            var document = new ThemeDocument(); var asset = new ThemeAsset { Kind = ThemeAssetKind.Video, PackagePath = "assets/video/malformed.mp4" };
            document.Assets.Add(asset); document.Widgets.Add(new WidgetModel { Type = WidgetType.Video, AssetId = asset.Id });
            using (var body = zip.CreateEntry(asset.PackagePath).Open()) body.Write(new byte[100]);
            using var json = zip.CreateEntry("theme.json").Open(); JsonSerializer.Serialize(json, document, Json);
        }
        SetDeclaredLengths(malformed, 200);
        ExpectInvalid(package.LoadAsync(malformed), awaitTask, "length");

        using var workspace = package.CreateNewWorkspace();
        var source = Path.Combine(root, "large-sparse-source.mp4");
        using (var file = File.Create(source)) file.SetLength(1024L * 1024 * 1024);
        for (var i = 0; i < 5; i++)
        {
            var asset = new ThemeAsset { Kind = ThemeAssetKind.Video, PackagePath = $"assets/video/save-{i}.mp4", LocalPath = source };
            workspace.Document.Assets.Add(asset); workspace.Document.Widgets.Add(new WidgetModel { Type = WidgetType.Video, AssetId = asset.Id });
        }
        var destination = Path.Combine(root, "preserved-existing.t3theme"); File.WriteAllText(destination, "existing original");
        ExpectInvalid(package.SaveAsync(workspace, destination), awaitTask, "4 GiB");
        Require(File.ReadAllText(destination) == "existing original" && !Directory.EnumerateFiles(root, "preserved-existing.t3theme.*.tmp").Any(), "Over-budget save must preserve the previous file and leave no temporary archive");
        workspace.Document.Widgets.Clear(); workspace.Document.Assets.Clear();
        var unsafeAsset = new ThemeAsset { Kind = ThemeAssetKind.Video, PackagePath = "../escaped.mp4", LocalPath = source };
        workspace.Document.Assets.Add(unsafeAsset); workspace.Document.Widgets.Add(new WidgetModel { Type = WidgetType.Video, AssetId = unsafeAsset.Id });
        ExpectInvalid(package.SaveAsync(workspace, destination), awaitTask, "Unsafe");
        Require(File.ReadAllText(destination) == "existing original", "Unsafe package path cannot overwrite the previous file");
        using var cancellation = new CancellationTokenSource(); cancellation.Cancel();
        try { awaitTask(package.LoadAsync(destination, cancellation.Token)); throw new Exception("Cancelled load succeeded"); } catch (OperationCanceledException) { }
        try { awaitTask(package.SaveAsync(workspace, destination, cancellation.Token)); throw new Exception("Cancelled save succeeded"); } catch (OperationCanceledException) { }
        Require(File.ReadAllText(destination) == "existing original", "Cancellation preserves the existing file");
    }

    private static void ExpectInvalid(Task task, Action<Task> awaitTask, string reason)
    {
        try { awaitTask(task); throw new InvalidOperationException("Invalid package operation succeeded"); }
        catch (InvalidDataException ex) { Require(ex.Message.Contains(reason, StringComparison.OrdinalIgnoreCase), "Wrong rejection: " + ex.Message); }
    }

    private static void CheckEditingDuringSave(string root, Action<Task> awaitTask)
    {
        var settings = new SettingsController(new AppSettingsService(Path.Combine(root, "package-save-settings.json")))
        { FirstRunCompleted = true, StartWithWindows = false, AutoStartDisplay = false };
        using var vm = new MainViewModel(settings, new SessionStateService(Path.Combine(root, "package-save-session")));
        vm.SetEditorActive(false);
        vm.Document.Name = "Before Save";
        var path = Path.Combine(root, "editor-frozen-save.t3theme");
        vm.Workspace.FilePath = path;
        var saving = vm.SaveCurrentThemeAsync();
        vm.Document.Name = "After Save click";
        awaitTask(saving);
        Require(vm.IsDirty && vm.HasUnsavedChanges && vm.Workspace.IsDirty, "Actual editor must preserve edits made during a package save");
        var loading = new ThemePackageService().LoadAsync(path); awaitTask(loading);
        using var loaded = loading.Result;
        Require(loaded.Document.Name == "Before Save", "Editor save writes its captured snapshot");
    }

    private static void CheckInactiveEmbeddedPhotoSession(string root, Action<Task> awaitTask)
    {
        var service = new ThemePackageService(); using var workspace = service.CreateNewWorkspace();
        var source = Path.Combine(root, "session-photo.png"); File.WriteAllText(source, "generated package image bytes");
        var importer = new AssetImportService();
        var inactivePhoto = importer.Import(workspace, source, ThemeAssetKind.Image);
        var activePhoto = importer.Import(workspace, source, ThemeAssetKind.Image);
        var orphan = importer.Import(workspace, source, ThemeAssetKind.Image);
        workspace.Document.Mode = ScreenMode.Hybrid;
        workspace.Document.PhotoFrame.Photos.Add(new PhotoFrameItem { AssetId = activePhoto.Id });
        var settings = new PhotoFrameSettings(); settings.Photos.Add(new PhotoFrameItem { AssetId = inactivePhoto.Id });
        var state = new SessionState { Themes = new ThemeSessionState { PhotoSettings = new() { [ScreenMode.PhotoFrame] = settings } } };
        var sessions = new SessionStateService(Path.Combine(root, "inactive-embedded-session"));
        awaitTask(sessions.SaveAsync(workspace, state));
        var restoring = sessions.LoadAsync(); awaitTask(restoring);
        using var restored = restoring.Result!.Workspace;
        Require(restored.Document.Assets.Count == 2 && restored.Document.Assets.All(a => File.Exists(restored.GetAbsolutePath(a))) && !restored.Document.Assets.Any(a => a.Id == orphan.Id),
            "Resume keeps embedded photos referenced by inactive mode settings, while omitting true orphan media");
        Require(restoring.Result.State.Themes.PhotoSettings[ScreenMode.PhotoFrame].Photos.Single().AssetId == inactivePhoto.Id, "Inactive playlist still points to its retained asset");
    }

    private static void SetDeclaredLengths(string path, long length)
    {
        // Tamper central-directory metadata only, avoiding multi-GiB fixtures for rejection cases.
        var bytes = File.ReadAllBytes(path);
        var end = bytes.Length - 22;
        while (end >= 0 && BitConverter.ToUInt32(bytes, end) != 0x06054b50) end--;
        Require(end >= 0, "ZIP end record");
        var offset = (int)BitConverter.ToUInt32(bytes, end + 16);
        while (BitConverter.ToUInt32(bytes, offset) == 0x02014b50)
        {
            var nameLength = BitConverter.ToUInt16(bytes, offset + 28);
            var name = System.Text.Encoding.UTF8.GetString(bytes, offset + 46, nameLength);
            if (name.StartsWith("assets/")) BitConverter.GetBytes(checked((uint)length)).CopyTo(bytes, offset + 24);
            offset += 46 + nameLength + BitConverter.ToUInt16(bytes, offset + 30) + BitConverter.ToUInt16(bytes, offset + 32);
        }
        File.WriteAllBytes(path, bytes);
    }
}
